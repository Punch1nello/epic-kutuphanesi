    private val dictionaries = mapOf(
        AppLanguage.TURKISH to tr,
        AppLanguage.ENGLISH to en,
        AppLanguage.GERMAN to de,
        AppLanguage.SPANISH to es,
        AppLanguage.RUSSIAN to ru
    )

    fun text(language: AppLanguage, key: String, vararg args: Any): String {
        val template = dictionaries[language]?.get(key) ?: en[key] ?: key
        return if (args.isEmpty()) template else String.format(Locale.forLanguageTag(language.localeTag), template, *args)
    }

    fun librarySubtitle(language: AppLanguage, count: Int, displayName: String): String {
        val word = when (language) {
            AppLanguage.TURKISH -> "oyun"
            AppLanguage.ENGLISH -> if (count == 1) "game" else "games"
            AppLanguage.GERMAN -> if (count == 1) "Spiel" else "Spiele"
            AppLanguage.SPANISH -> if (count == 1) "juego" else "juegos"
            AppLanguage.RUSSIAN -> {
                val mod100 = count % 100
                val mod10 = count % 10
                when {
                    mod100 in 11..14 -> "игр"
                    mod10 == 1 -> "игра"
                    mod10 in 2..4 -> "игры"
                    else -> "игр"
                }
            }
        }
        return "$count $word · $displayName"
    }

    fun genre(language: AppLanguage, id: String): String {
        val key = when (id) {
            "action", "action_adventure", "adventure", "rpg", "strategy", "simulation", "sports", "racing",
            "shooter", "fps", "tps", "platformer", "puzzle", "horror", "survival", "indie", "open_world",
            "fighting", "family", "casual", "card", "mmo", "mmorpg", "free_to_play", "metroidvania",
            "roguelike", "roguelite", "turn_based", "tower_defense", "city_builder", "sandbox", "stealth", "soulslike" -> "genre_$id"
            else -> "genre_other"
        }
        return text(language, key)
    }

    fun playtime(language: AppLanguage, minutes: Long?): String {
        if (minutes == null) return text(language, "playtime_unknown")
        val hours = minutes / 60L
        val remainingMinutes = minutes % 60L
        return when {
            hours > 0L && remainingMinutes > 0L -> text(language, "playtime_hours_minutes", hours, remainingMinutes)
            hours > 0L -> text(language, "playtime_hours", hours)
            else -> text(language, "playtime_minutes", minutes)
        }
    }
